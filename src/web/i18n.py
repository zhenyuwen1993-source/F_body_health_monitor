def normalize_lang(lang: str | None) -> str:
    if not lang:
        return DEFAULT_LANG
    lang = str(lang).lower()
    if lang.startswith("en"):
        return "en"
    if lang.startswith("zh"):
        return "zh"
    return DEFAULT_LANG if lang not in SUPPORTED else lang


def get_lang() -> str:
    """Read language from Streamlit session when available."""
    try:
        import streamlit as st

        return normalize_lang(st.session_state.get("lang", DEFAULT_LANG))
    except Exception:
        return DEFAULT_LANG


def t(key: str, lang: str | None = None, **kwargs: Any) -> str:
    """Translate key; falls back to Chinese then to the key itself."""
    lang = normalize_lang(lang)
    table = _MESSAGES.get(lang) or _MESSAGES[DEFAULT_LANG]
    text = table.get(key) or _MESSAGES[DEFAULT_LANG].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def tr(key: str, **kwargs: Any) -> str:
    """Translate using current session language."""
    return t(key, get_lang(), **kwargs)


def intent_label(intent: str | None, lang: str | None = None, *, full: bool = False) -> str:
    mapping = {
        "restore": "intent_restore",
        "maintain": "intent_maintain_full" if full else "intent_maintain",
        "perform": "intent_perform",
    }
    key = mapping.get(intent or "", "")
    if not key:
        return intent or "—"
    return t(key, lang)


def band_label(band: str | None, lang: str | None = None) -> str:
    mapping = {
        "green": "band_green",
        "yellow": "band_yellow",
        "red": "band_red",
        "unknown": "band_unknown",
    }
    return t(mapping.get(band or "unknown", "band_unknown"), lang)
